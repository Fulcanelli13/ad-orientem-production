import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const json=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const manifest=json('app-data/sacred-art/devotional-asset-recovery-20261116.v1.json');
const gallery=json('site/gallery/catalogue.v1.json');
const images=json('site/gallery/image-provenance.v1.json');
const oldIndex=json('app-data/sacred-art/artwork-assignment-index.v2.json');
const prior=json('app-data/sacred-art/source-master-migration-20261116.v1.json');
assert.equal(manifest.schema,'ao.sacred-art.exact-devotional-asset-recovery.v1');
assert.equal(manifest.assets.length,3);
assert.equal(manifest.summary.exact_assets,3);
assert.equal(manifest.summary.actual_copied_bytes,4607313);
assert.equal(manifest.summary.newly_copied_from_old_repo,2);
assert.equal(manifest.summary.reused_existing_permanent_source_master,1);
assert.equal(manifest.summary.new_gallery_paintings,2);
assert.equal(manifest.summary.nonpainting_archival_portraits,1);
assert.equal(manifest.summary.held_approved_painting_photos,1);
assert.equal(manifest.summary.new_catalogue_records,0);
assert.equal(manifest.summary.new_prayer_defaults,0);
assert.equal(manifest.summary.hash_mismatches,0);
assert.equal(gallery.counts.total_records,873);
assert.equal(gallery.counts.distinct_locally_hosted_paintings,234);
assert.equal(gallery.counts.image_available_records,237);
assert.equal(gallery.counts.verified_image_files,234);
assert.equal(images.sources.length,234);
assert.equal(gallery.records.length,873);
assert.equal(new Set(gallery.records.map(x=>x.id)).size,873);
assert.equal(oldIndex.artworks.length,862);
for(const old of oldIndex.artworks){
 const row=gallery.records.find(x=>x.id===old.artwork_id);
 assert(row);
 assert.equal(row.title,old.title||'Untitled');
 assert.equal(row.artist,old.artist||'Artist not documented');
 assert.deepEqual(row.exact_prayer_cards,old.owner_approved_exact_card_ids);
 assert.equal(row.eligible_card_count,old.candidate_prayer_card_ids.length);
 assert.equal(row.attribution_status,old.attribution_status);
}
let total=0;
for(const a of manifest.assets){
 const filepath=a.gallery_path??a.archive_path;
 assert(filepath);
 assert(a.source_ref==='14cd9d3ac11a6f27856f4740ae7c81e1b073bf1a');
 const bytes=fs.readFileSync(filepath);
 assert.equal(bytes.length,a.bytes,a.key+' bytes');
 assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),a.sha256,a.key+' SHA256');
 assert.equal(crypto.createHash('sha1').update(Buffer.from('blob '+bytes.length+'\0')).update(bytes).digest('hex'),a.git_blob_sha,a.key+' Git SHA');
 assert(a.rights);
 assert(a.source_page.startsWith('https://'));
 total+=bytes.length;
 if(a.gallery_published){
   assert(filepath.startsWith('site/gallery/images/'));
   const row=gallery.records.find(x=>x.id===a.catalogue_id);
   assert(row);
   assert.equal(row.image.src,'./'+filepath.slice('site/'.length));
   assert.equal(row.image.usage,'GALLERY_IMAGE_ONLY__PRAYER_DEFAULTS_UNCHANGED');
   assert(row.image.license);
   assert(row.image.license_url.startsWith('https://'));
   const proof=images.sources.find(x=>x.path===filepath);
   assert(proof);
   assert.equal(proof.sha256,a.sha256);
   assert.equal(proof.git_blob_sha,a.git_blob_sha);
   assert.equal(proof.release_scope,'GALLERY_IMAGE_ONLY__NO_NEW_PRAYER_DEFAULT');
 }
}
assert.equal(total,4607313);
const mystic=manifest.assets.find(x=>x.key==='mystic_lamb');
const therese=manifest.assets.find(x=>x.key==='st_therese');
const murillo=manifest.assets.find(x=>x.key==='murillo_confession');
assert(mystic&&!mystic.source_original_jpeg_preserved);
assert(mystic.rights.includes('NOT a CC0 licence'));
assert.equal(mystic.old_approval,'APPROVED_THEMATIC_SCENE');
assert(!therese.gallery_published);
assert(therese.archive_path.startsWith('app-data/sacred-art/devotional-portraits/'));
assert.deepEqual(therese.source_image_dimensions,[362,498]);
assert.equal(therese.old_approval,'FINAL_PHOTOGRAPH_APPROVED');
assert(murillo.source_original_jpeg_preserved);
const oldMurillo=prior.inventory.find(z=>z.master_path===murillo.existing_master);
assert.equal(oldMurillo.source_release_pr,2293);
assert.deepEqual(fs.readFileSync(murillo.gallery_path),fs.readFileSync(murillo.existing_master));
const held=manifest.held_photographs;
assert.equal(held.length,1);
assert.equal(held[0].artwork_id,'HERO::mnac:008327-000');
assert.equal(held[0].copied,false);
assert.equal(held[0].gallery_published,false);
assert.equal(gallery.records.find(x=>x.id===held[0].artwork_id).image,null);
const art=gallery.records.find(x=>x.id==='PRAYER::saints--vaneyck');
assert(art.image.scene_use_note.includes('not the priest'));
const ui=fs.readFileSync('site/gallery/gallery.js','utf8');
assert(ui.includes('item.image.scene_use_note'));
assert(ui.includes('item.image.license_url'));
console.log('PASS: exact Mystic Lamb and St Therese archived WebP bytes, Murillo NGA master reuse; 870 records, 70 paintings, no Seven Sorrows release or new prayer default.');
