import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync, existsSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const path=p=>resolve(root,p);
const bytes=p=>readFileSync(path(p));
const json=p=>JSON.parse(bytes(p).toString('utf8'));
const sha=p=>createHash('sha256').update(bytes(p)).digest('hex');
const previous=json('app-data/sacred-art/selected31-clearance-v21.json');
const current=json('app-data/sacred-art/selected31-clearance-v22.json');
const hold=json('app-data/sacred-art/selected31-held-remediation-v22.json');
const owner=json('app-data/sacred-art/selected31-original-owner-jordaens-evidence-v22.json');
const archive15=json('app-data/sacred-art/staged-selected31-v15/acquisition-results.v15.json');
const archive18=json('app-data/sacred-art/staged-selected31-v18/acquisition-results.v18.json');
const ov=json('site/gallery/selected31-reviewed-images.v22.json');
const base=json('site/gallery/catalogue.v1.json');
const provenance=json('site/gallery/image-provenance.v1.json');
const loader=bytes('site/gallery/gallery.js').toString('utf8');
assert.equal(current.schema,'ao.sacred-art.selected31-clearance.v22');
assert.equal(current.records.length,31);
assert.equal(previous.records.length,31);
assert.deepEqual(current.counts,{main_preserved:7,overlay_eligible:11,source_only_holds:13});
assert.equal(hold.counts.held,13);
assert.equal(hold.records.length,13);
assert.deepEqual(new Set(hold.records.map(x=>x.review_artwork_id)),new Set(current.records.filter(x=>x.disposition==='HOLD_SOURCE_ONLY').map(x=>x.review_artwork_id)));
assert.equal(base.counts.total_records,873);
assert.equal(base.counts.distinct_locally_hosted_paintings,472);
assert.equal(provenance.local_image_count,472);
assert.equal(provenance.sources.length,472);
assert.equal(ov.schema,'ao.sacred-art.selected31-gallery-overlay.v22');
assert.equal(ov.new_review_records,2);
assert.equal(ov.records.length,2);
assert.equal(ov.provenance.length,2);
assert.deepEqual(ov.records.map(x=>x.id),['REVIEW31::euch-tiepolo','REVIEW31::king-jordaens']);
const newIds=current.records.filter(x=>x.disposition!==previous.records.find(y=>y.review_artwork_id===x.review_artwork_id)?.disposition).map(x=>x.review_artwork_id).sort();
assert.deepEqual(newIds,['euch-tiepolo','king-jordaens']);
for(const x of ov.records){
 assert(x.owner_selected_artwork);
 assert(x.exact_prayer_cards.length===0&&x.prayer_parts.length===0&&x.parent_prayer_candidates.length===0&&x.eligible_card_count===0);
 assert(x.image?.src?.startsWith('./gallery/images/selected31-v22-'));
 assert(existsSync(path('site/'+x.image.src.slice(2))));
}
const a=archive15.records.find(x=>x.review_artwork_id==='euch-tiepolo');
const b=archive18.records.find(x=>x.review_artwork_id==='king-jordaens');
assert(a&&b);
assert.deepEqual(a.source_dimensions,[2676,2304]);
assert.deepEqual(b.source_dimensions,[6437,5891]);
assert.equal(owner.source_review_identifier,'king-jordaens');
assert.equal(owner.literal_original_v12_fields.inventory,'SMK KMSsp234');
assert(owner.literal_original_v12_fields.identity_status.includes('CATALOGUE_ID'));
assert.equal(owner.photo_research_v18.museum_attribution,'Attributed to Jacob Jordaens');
assert.equal(ov.records[1].artist,'Attributed to Jacob Jordaens');
assert.equal(ov.records[1].institution,'Statens Museum for Kunst, Copenhagen · KMSsp234');
const pairs=[{src:a,idx:0},{src:b,idx:1}];
for(const {src,idx} of pairs){
 const row=ov.records[idx],p=ov.provenance[idx];
 const filename='site/'+row.image.src.slice(2);
 assert.equal(sha(src.source_path),src.source_sha256,'Archive original must match manifest');
 assert.equal(sha(src.derivative_path),src.derivative_sha256,'Research derivative must match manifest');
 assert.equal(sha(filename),src.derivative_sha256,'Gallery derivative identical byte-wise');
 assert.equal(p.source_sha256,src.source_sha256);
 assert.equal(p.derivative_sha256,src.derivative_sha256);
 assert.equal(p.gallery_file,filename);
 assert.deepEqual([row.image.pixel_width,row.image.pixel_height],src.derivative_dimensions);
}
assert.equal(ov.records[0].image.license,'CC BY 3.0');
assert.equal(ov.records[0].image.photographer,'Sailko');
assert(ov.records[0].image.license_url.includes('/by/3.0/'));
assert.equal(ov.records[1].image.license,'CC0 1.0');
assert(ov.records[1].image.license_url.includes('/zero/1.0/'));
assert(ov.records[0].image.adaptation.includes('without cropping'));
assert(ov.records[1].image.adaptation.includes('no crop'));
const champ=current.records.find(x=>x.review_artwork_id==='euch-champaigne');
assert.equal(champ.disposition,'HOLD_SOURCE_ONLY');
assert(champ.visual_gate.includes('LEFT_EDGE_CUT'));
assert(champ.rights_gate.includes('TANGOPASO_PD_SELF'));
for(const row of current.records){
 assert.equal(row.automatic_prayer_card_assignment,false);
 if(row.disposition==='HOLD_SOURCE_ONLY')assert(existsSync(path(row.source_archive_path)),row.review_artwork_id);
}
assert(loader.includes('selected31-reviewed-images.v22.json'));
assert(loader.includes('legacyRecordCount !== 873 || addedRecords !== 10 || addedImages !== 11'));
assert.equal(873+10,883);
assert.equal(472+11,483);
