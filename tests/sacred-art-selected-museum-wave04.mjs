import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const report=read('app-data/sacred-art/selected-museum-image-wave04-20261116.v1.json');
const gallery=read('site/gallery/catalogue.v1.json');
const prov=read('site/gallery/image-provenance.v1.json');
const prior=read('app-data/sacred-art/bulk-museum-image-queue-20261116.v1.json');
const rejects=read('app-data/sacred-art/legacy-artwork-rejections-20261116.v1.json');
const canon=read('app-data/sacred-art/artwork-assignment-index.v2.json');
const first=read('app-data/sacred-art/bulk-commons-photo-import-20261116.v1.json');
const second=read('app-data/sacred-art/bulk-commons-photo-import-batch02-20261116.v1.json');
const third=read('app-data/sacred-art/commons-rate-limit-recovery-wave03-20261116.v1.json');
assert.equal(report.schema,'ao.sacred-art.exact-selected-museum-source-acquisition-wave04.v1');
assert.equal(report.summary.reviewed_owner_selected_records,90);
const n=report.summary.new_gallery_paintings;
assert(n>=4 && n<=90);
assert.equal(report.artworks.length,n);
assert.equal(report.held.length,90-n);
assert.equal(report.decisions.length,90);
assert.equal(new Set(report.decisions.map(x=>x.artwork_id)).size,90);
assert.equal(report.summary.held_count,90-n);
assert.equal(report.summary.original_catalogue_records_preserved,873);
assert.equal(report.summary.historical_rejected_originals_preserved,103);
assert.equal(report.summary.new_prayer_card_assignments,0);
assert.equal(report.summary.new_calendar_placements,0);
assert.equal(report.summary.original_source_master_jpeg_bank_unchanged,54);
assert.equal(report.summary.fingerprint_mismatches,0);
assert.equal(gallery.records.length,873);
assert.equal(gallery.counts.total_records,873);
assert.equal(gallery.counts.distinct_locally_hosted_paintings,392+n);
assert.equal(gallery.counts.image_available_records,395+n);
assert.equal(gallery.counts.verified_image_files,392+n);
assert.equal(prov.sources.length,392+n);
assert.equal(prov.local_image_count,392+n);
assert.equal(prov.catalogue_record_images_count,395+n);
assert.equal(first.assets.length,161);
assert.equal(second.assets.length,109);
assert.equal(third.assets.length,49);
assert.equal(rejects.rejected_originals.length,103);
assert.equal(canon.artworks.length,862);
assert.equal(prior.counts.image_missing_other_selected,90);
const oldIDs=new Set(prior.museum_and_other_selected_queue.map(x=>x.artwork_id));
const bannedURLs=new Set(rejects.rejected_originals.map(x=>decodeURIComponent(x.source_url||'').replace(/_/g,' ').toLowerCase()));
const held=new Set(report.held.map(x=>x.artwork_id));
const released=new Set();
let total=0;
for(const a of report.artworks){
 assert(oldIDs.has(a.artwork_id),'Never introduce a newly selected artwork');
 assert(!released.has(a.artwork_id));
 released.add(a.artwork_id);
 assert(!held.has(a.artwork_id),'Previously held source may not be released');
 assert(!bannedURLs.has(decodeURIComponent(a.artwork_source_url||'').replace(/_/g,' ').toLowerCase()));
 assert(a.derivative_path.startsWith('site/gallery/images/selected-museum-wave04-'));
 assert(a.derivative_path.endsWith('.webp'));
 const bytes=fs.readFileSync(a.derivative_path);
 assert.equal(bytes.subarray(0,4).toString(),'RIFF');
 assert.equal(bytes.subarray(8,12).toString(),'WEBP');
 assert.equal(bytes.length,a.derivative_bytes);
 assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),a.derivative_sha256);
 assert.equal(crypto.createHash('sha1').update(Buffer.from('blob '+bytes.length+'\0')).update(bytes).digest('hex'),a.derivative_git_blob);
 assert.equal(a.full_original_photograph_archived,false);
 assert(a.derivative_pixels.every(x=>x>=700));
 assert.equal(a.photo_license_evidence.copyrighted_flag,'false');
 assert(a.photo_license_evidence.license_short);
 const row=gallery.records.find(r=>r.id===a.artwork_id);
 assert(row && row.owner_selected_artwork===true);
 assert.equal(row.title,a.title);
 assert.equal(row.artist,a.artist);
 assert.equal(row.record_status,a.historical_curation);
 assert.equal(row.rights_note,a.historical_rights_note);
 assert.equal(row.image.src,'./'+a.derivative_path.slice('site/'.length));
 assert.equal(row.image.usage,'GALLERY_ONLY__PREVIOUSLY_SELECTED__NO_NEW_PRAYER_OR_CALENDAR_ASSIGNMENTS');
 assert.equal(row.image.license_url,a.source_file_page);
 const pp=prov.sources.find(x=>x.artwork_id===a.artwork_id&&x.path===a.derivative_path);
 assert(pp);
 assert.equal(pp.sha256,a.derivative_sha256);
 assert.equal(pp.git_blob_sha,a.derivative_git_blob);
 assert.equal(pp.original_full_resolution_bytes_archived,false);
 assert.equal(pp.release_scope,'GALLERY_ONLY__NO_NEW_PRAYER_OR_CALENDAR');
 assert(a.source_method.startsWith('OWNER_SELECTED_COMMONS_EXACT_FILE')||a.source_method.startsWith('OFFICIAL_'));
 if(a.source_method.startsWith('OWNER_SELECTED_COMMONS')){
  assert(a.source_file_page.startsWith('https://commons.wikimedia.org/wiki/File:'));
  assert(['false','0','no'].includes(a.photo_license_evidence.copyrighted_flag));
  assert(/public domain|cc0/i.test(a.photo_license_evidence.license_short));
 }
 total+=bytes.length;
}
assert.equal(total,report.summary.new_derivative_bytes);
for(const h of report.held){
 assert(oldIDs.has(h.artwork_id));
 const row=gallery.records.find(r=>r.id===h.artwork_id);
 assert(row && row.image===null,'Every rights, photograph and quality hold must remain unpictured');
}
for(const old of canon.artworks){
 const row=gallery.records.find(r=>r.id===old.artwork_id);
 assert(row);
 assert.deepEqual(row.exact_prayer_cards,old.owner_approved_exact_card_ids);
 assert.equal(row.eligible_card_count,old.candidate_prayer_card_ids.length);
 assert.equal(row.attribution_status,old.attribution_status);
}
assert(fs.readFileSync('site/gallery/gallery.js','utf8').includes('data.records?.length !== 873'));
console.log('PASS: wave04 '+n+' exact previously selected Commons/museum local images, '+total+' bytes, '+(90-n)+' holds; 103 rejected objects protected; 873 artworks and all prayer associations preserved.');
