import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const j=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const transfer=j('app-data/sacred-art/san-polo-released-cycle-migration.v1.json');
const gallery=j('site/gallery/catalogue.v1.json');
const provenance=j('site/gallery/image-provenance.v1.json');
const historical=j('app-data/sacred-art/artwork-assignment-index.v2.json');
assert.equal(transfer.schema,'ao.sacred-art.san-polo-released-14-exact-transfer.v1');
assert.equal(transfer.files.length,14);
assert.equal(transfer.summary.files,14);
assert.equal(transfer.summary.bytes,15141828);
assert.equal(transfer.summary.existing_gallery_records_linked,6);
assert.equal(transfer.summary.new_records_for_previously_selected_works,8);
assert.equal(transfer.summary.new_prayer_defaults,0);
assert.equal(transfer.summary.sha256_failures,0);
assert.equal(transfer.summary.blob_sha_failures,0);
assert.equal(gallery.records.length,873);
assert.equal(gallery.counts.total_records,873);
assert.equal(gallery.counts.image_available_records,475);
assert.equal(gallery.counts.distinct_locally_hosted_paintings,472);
assert.equal(gallery.counts.verified_image_files,472);
assert.equal(provenance.sources.length,472);
assert.equal(historical.artworks.length,862);
for(const old of historical.artworks){
  const work=gallery.records.find(x=>x.id===old.artwork_id);
  assert(work,'Historical artwork missing from gallery: '+old.artwork_id);
  assert.deepEqual(work.exact_prayer_cards,old.owner_approved_exact_card_ids);
  assert.equal(work.eligible_card_count,old.candidate_prayer_card_ids.length);
  assert.equal(work.attribution_status,old.attribution_status);
}
const seenFiles=new Set();
const seenWorks=new Set();
let bytes=0, added=0, linked=0;
for(const x of transfer.files){
  assert(Number.isInteger(x.station)&&x.station>=1&&x.station<=14);
  assert(!seenWorks.has(x.station),'Duplicate Station number');
  seenWorks.add(x.station);
  assert.equal(x.source_ref,transfer.old_commit);
  assert.equal(x.prior_release_pr,2699);
  assert.equal(x.license,'CC BY-SA 4.0');
  assert.equal(x.license_url,'https://creativecommons.org/licenses/by-sa/4.0/');
  assert.match(x.photographer,/Didier Descouens/);
  assert.match(x.source_url,/^https:\/\/commons\.wikimedia\.org\/wiki\/File:/);
  assert.equal(x.usage,'GALLERY_IMAGE_ONLY__NO_NEW_PRAYER_DEFAULT');
  assert.equal(x.original_jpeg_preserved_in_production,false);
  assert(!seenFiles.has(x.local_path));
  seenFiles.add(x.local_path);
  const buf=fs.readFileSync(x.local_path);
  assert.equal(buf.length,x.bytes);
  assert.equal(crypto.createHash('sha256').update(buf).digest('hex'),x.source_sha256);
  assert.equal(crypto.createHash('sha1').update(Buffer.from('blob '+buf.length+'\0')).update(buf).digest('hex'),x.source_git_blob_sha);
  assert.equal(buf.subarray(0,4).toString(),'RIFF');
  assert.equal(buf.subarray(8,12).toString(),'WEBP');
  bytes+=buf.length;
  assert.equal(x.existing_or_added_gallery_ids.length,1);
  const row=gallery.records.find(z=>z.id===x.existing_or_added_gallery_ids[0]);
  assert(row);
  assert.equal(row.image?.src,'./'+x.local_path.slice('site/'.length));
  assert.equal(row.image?.photographer,'Didier Descouens / Archaeodontosaurus');
  assert.equal(row.image?.license,'CC BY-SA 4.0');
  assert.equal(row.image?.usage,'GALLERY_IMAGE_ONLY__NO_NEW_PRAYER_DEFAULT');
  if(x.new_registry_record){
    added++;
    assert(x.existing_or_added_gallery_ids[0].startsWith('RELEASED::san-polo-oils:station-'));
    assert.deepEqual(row.exact_prayer_cards,[]);
    assert.equal(row.owner_selected_artwork,true);
    assert.equal(row.eligible_card_count,0);
  } else {
    linked++;
    assert(historical.artworks.some(z=>z.artwork_id===row.id));
  }
  const image=provenance.sources.find(y=>y.path===x.local_path);
  assert(image);
  assert.equal(image.sha256,x.source_sha256);
  assert.equal(image.git_blob_sha,x.source_git_blob_sha);
  assert.equal(image.source_photograph_license,'CC BY-SA 4.0');
  assert.equal(image.release_scope,'GALLERY_ONLY__PRAYER_DEFAULTS_UNCHANGED');
}
assert.equal(bytes,15141828);
assert.equal(seenFiles.size,14);
assert.equal(seenWorks.size,14);
assert.equal(added,8);
assert.equal(linked,6);
const license=fs.readFileSync('site/gallery/SAN-POLO-LICENSE-ATTRIBUTION.md','utf8');
assert(license.includes('Didier Descouens'));
assert(license.includes('CC BY-SA 4.0'));
assert(license.includes('Station XIV'));
const ui=fs.readFileSync('site/gallery/gallery.js','utf8');
assert(ui.includes('item.image.photographer'));
assert(ui.includes('item.image.license_url'));
assert(ui.includes('item.image.adaptation'));
const html=fs.readFileSync('site/index.html','utf8');
assert.equal((html.match(/class="tab(?: active)?"/g)||[]).length,4);
console.log('PASS: 14 previously released San Polo images, exactly 15,141,828 bytes; 862 old artworks preserved; 8 added records; no prayer defaults, exact credits/licence present.');
