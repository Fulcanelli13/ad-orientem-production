import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const json=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const wave=json('app-data/sacred-art/commons-rate-limit-recovery-wave03-20261116.v1.json');
const audit=json('app-data/sacred-art/bulk-museum-image-queue-20261116.v1.json');
const prior=json('app-data/sacred-art/bulk-commons-photo-import-batch02-20261116.v1.json');
const wave04=json('app-data/sacred-art/selected-museum-image-wave04-20261116.v1.json');
const n04=wave04.summary.new_gallery_paintings;
const first=json('app-data/sacred-art/bulk-commons-photo-import-20261116.v1.json');
const gallery=json('site/gallery/catalogue.v1.json');
const prov=json('site/gallery/image-provenance.v1.json');
const source=json('app-data/sacred-art/artwork-assignment-index.v2.json');
const reject=json('app-data/sacred-art/legacy-artwork-rejections-20261116.v1.json');
assert.equal(wave.schema,'ao.sacred-art.bulk-commons-rate-limit-recovery.v1');
assert.equal(wave.only_prior_429_items,49);
assert.equal(wave.small_image_held,2);
assert.equal(wave.summary.retry_queue,51);
assert.equal(wave.summary.previous_rate_limited,49);
assert.equal(wave.assets.length+wave.held.length,51);
assert.equal(wave.summary.recovered_images,wave.assets.length);
assert.equal(wave.summary.held_after_retry,wave.held.length);
assert.equal(wave.summary.historical_catalogue_records_unchanged,873);
assert.equal(wave.summary.new_prayer_assignments,0);
assert.equal(wave.summary.new_calendar_assignments,0);
assert.equal(wave.summary.rejected_source_items_protected,103);
const n=wave.assets.length;
assert(n<=49);
assert.equal(gallery.records.length,873);
assert.equal(gallery.counts.total_records,873);
assert.equal(gallery.counts.distinct_locally_hosted_paintings,343+n+n04);
assert.equal(gallery.counts.image_available_records,346+n+n04);
assert.equal(gallery.counts.verified_image_files,343+n+n04);
assert.equal(prov.sources.length,343+n+n04);
assert.equal(prov.local_image_count,343+n+n04);
assert.equal(prov.catalogue_record_images_count,346+n+n04);
assert.equal(first.assets.length,161);
assert.equal(prior.assets.length,109);
assert.equal(source.artworks.length,862);
assert.equal(reject.rejected_originals.length,103);
const holds=new Map(prior.held.map(h=>[h.artwork_id,h]));
const excluded=new Set(reject.rejected_originals.map(h=>decodeURIComponent(h.source_url||'').replace(/_/g,' ').toLowerCase()));
const ids=new Set();
let total=0;
for(const a of wave.assets){
 assert(!ids.has(a.artwork_id));ids.add(a.artwork_id);
 assert(holds.has(a.artwork_id));
 assert.equal(holds.get(a.artwork_id).reason,'IMAGE_DOWNLOAD_DECODE_OR_QUALITY_FAILED');
 assert(holds.get(a.artwork_id).detail.includes('HTTP Error 429'));
 assert(!excluded.has(decodeURIComponent(a.source_page).replace(/_/g,' ').toLowerCase()));
 assert(a.derivative_path.startsWith('site/gallery/images/owner-approved-20261103-'));
 assert(a.derivative_path.endsWith('.webp'));
 const b=fs.readFileSync(a.derivative_path);
 assert.equal(b.subarray(0,4).toString(),'RIFF');
 assert.equal(b.subarray(8,12).toString(),'WEBP');
 assert.equal(b.length,a.derivative_bytes);
 assert.equal(crypto.createHash('sha256').update(b).digest('hex'),a.derivative_sha256);
 assert.equal(crypto.createHash('sha1').update(Buffer.from('blob '+b.length+'\0')).update(b).digest('hex'),a.derivative_git_blob_sha);
 assert(a.derivative_dimensions.every(z=>z>=700));
 assert(['false','0','no'].includes(a.license_evidence.copyrighted_flag));
 assert(a.license_evidence.license_short.includes('public domain')||a.license_evidence.license_short.includes('cc0'));
 assert(a.original_bytes_archived===false);
 const rec=gallery.records.find(r=>r.id===a.artwork_id);
 assert(rec && rec.owner_selected_artwork);
 assert.equal(rec.record_status,'APPROVED_BY_USER_2026_11_03');
 assert.equal(rec.image.src,'./'+a.derivative_path.slice('site/'.length));
 assert.equal(rec.image.usage,'GALLERY_ONLY__USER_SELECTED_WORK__NO_NEW_PRAYER_DEFAULT');
 const p=prov.sources.find(p=>p.artwork_id===a.artwork_id && p.path===a.derivative_path);
 assert(p && p.sha256===a.derivative_sha256);
 assert.equal(p.source_image_original_bytes_retained,false);
 total+=b.length;
}
assert.equal(total,wave.summary.added_webp_bytes);
for(const h of wave.held){
 assert(holds.has(h.artwork_id));
 assert(!ids.has(h.artwork_id));
 const rec=gallery.records.find(r=>r.id===h.artwork_id);
 assert(rec && rec.image===null);
}
assert.equal(audit.schema,'ao.sacred-art.bulk-gallery-museum-candidate-inventory.v1');
assert.equal(audit.counts.catalogue_records,873);
assert.equal(audit.counts.gallery_paintings,343,'Museum audit captures unmodified pre-retry state');
assert.equal(audit.counts.image_bearing_records,346);
assert.equal(audit.counts.image_missing_november3_commons,305,'Broader RECENT575 source group includes 84 other historical image-missing rows beyond the 221 batch-02 holds');
assert.equal(audit.counts.image_missing_all,527);
assert.equal(audit.counts.image_missing_other_selected,audit.museum_and_other_selected_queue.length);
assert.equal(audit.counts.archival_original_master_matches,audit.existing_master_matches.length);
assert.equal(audit.previous_commons_remaining_holds,221);
for(const old of source.artworks){
 const row=gallery.records.find(r=>r.id===old.artwork_id);
 assert(row);
 assert.equal(row.attribution_status,old.attribution_status);
 assert.deepEqual(row.exact_prayer_cards,old.owner_approved_exact_card_ids);
}
console.log('PASS: wave03 polite Commons recovery of '+n+' exact owner-selected files, '+total+' bytes; museum queue of '+audit.museum_and_other_selected_queue.length+' previously selected records indexed without new placements.');
