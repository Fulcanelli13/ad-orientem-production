assert(ui.includes('data.records?.length !== 873'));
console.log('PASS bulk selected Sacred Art: '+n+' full-composition locally archived WebPs, '+bytes+' bytes, 491-record historical review, 103 explicit rejections protected; 873 stable catalogue rows, zero new prayer assignments.');
