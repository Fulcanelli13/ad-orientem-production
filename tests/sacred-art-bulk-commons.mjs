import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const read=path=>JSON.parse(fs.readFileSync(path,'utf8'));
const gallery=read('site/gallery/catalogue.v1.json');
const prov=read('site/gallery/image-provenance.v1.json');
const manifest=read('app-data/sacred-art/bulk-commons-photo-import-20261116.v1.json');
const batch02=read('app-data/sacred-art/bulk-commons-photo-import-batch02-20261116.v1.json');
const n02=batch02.summary.new_gallery_images;
const wave03=read('app-data/sacred-art/commons-rate-limit-recovery-wave03-20261116.v1.json');
const n03=wave03.summary.recovered_images;
const wave04=read('app-data/sacred-art/selected-museum-image-wave04-20261116.v1.json');
const n04=wave04.summary.new_gallery_paintings;
const wave05=read('app-data/sacred-art/curated-cohort-image-wave05-20261116.v1.json');
const n05=wave05.summary.new_gallery_images;
const quality06=read('app-data/sacred-art/quality-recovery-wave06-20261116.v1.json');
const n06=quality06.summary.new_gallery_paintings;
const rejected=read('app-data/sacred-art/legacy-artwork-rejections-20261116.v1.json');
const originals=read('app-data/sacred-art/artwork-assignment-index.v2.json');
assert.equal(manifest.schema,'ao.sacred-art.bulk-approved-commons-source-import.v1');
assert.equal(rejected.rejected_originals.length,103);
assert.equal(rejected.count,103);
const n=manifest.summary.new_gallery_images;
assert(n>=25,'Must perform a genuinely useful batch rather than one-off art migration');
assert(n<=180);
assert.equal(manifest.assets.length,n);
assert.equal(gallery.records.length,873);
assert.equal(gallery.counts.total_records,873);
assert.equal(gallery.counts.selected_artwork_records,740);
assert.equal(gallery.counts.distinct_locally_hosted_paintings,73+n+n02+n03+n04+n05+n06);
assert.equal(gallery.counts.image_available_records,76+n+n02+n03+n04+n05+n06);
assert.equal(gallery.counts.verified_image_files,73+n+n02+n03+n04+n05+n06);
assert.equal(prov.sources.length,73+n+n02+n03+n04+n05+n06);
assert.equal(prov.local_image_count,73+n+n02+n03+n04+n05+n06);
assert.equal(prov.catalogue_record_images_count,76+n+n02+n03+n04+n05+n06);
assert.equal(originals.artworks.length,862);
for(const old of originals.artworks){
 const r=gallery.records.find(x=>x.id===old.artwork_id);
 assert(r,'preserve historical artwork '+old.artwork_id);
 assert.equal(r.attribution_status,old.attribution_status);
 assert.deepEqual(r.exact_prayer_cards,old.owner_approved_exact_card_ids);
 assert.equal(r.eligible_card_count,old.candidate_prayer_card_ids.length);
}
const exact=new Set(),pages=new Set(),blobs=new Set();
const rejectedURLs=new Set(rejected.rejected_originals.map(x=>decodeURIComponent(x.source_url||'').replace(/_/g,' ').toLowerCase()));
let bytes=0;
for(const a of manifest.assets){
 assert(a.artwork_id.startsWith('RECENT575::'));
 assert(!exact.has(a.artwork_id),'duplicate artwork');
 assert(!pages.has(a.commons_pageid),'duplicate Commons image');
 exact.add(a.artwork_id);pages.add(a.commons_pageid);
 assert(a.derivative_path.startsWith('site/gallery/images/owner-approved-20261103-'));
 assert(a.derivative_path.endsWith('.webp'));
 const b=fs.readFileSync(a.derivative_path);
 assert.equal(b.slice(0,4).toString(),'RIFF');
 assert.equal(b.slice(8,12).toString(),'WEBP');
 assert.equal(b.length,a.derivative_bytes);
 assert.equal(crypto.createHash('sha256').update(b).digest('hex'),a.derivative_sha256);
 assert.equal(crypto.createHash('sha1').update(Buffer.from('blob '+b.length+'\0')).update(b).digest('hex'),a.derivative_git_blob_sha);
 assert(!blobs.has(a.derivative_git_blob_sha),'duplicate physical derivative');
 blobs.add(a.derivative_git_blob_sha);
 assert.equal(a.original_bytes_archived,false);
 assert(a.original_dimensions.every(v=>v>=1050));
 assert(a.derivative_dimensions.every(v=>v>=700));
 assert(['false','0','no'].includes(a.license_evidence.copyrighted_flag));
 assert(a.license_evidence.license_short.includes('public domain')||a.license_evidence.license_short.includes('cc0'));
 assert(!/by-sa|by-nc|cc by|all rights reserved/i.test(a.license_evidence.license_short));
 assert(!rejectedURLs.has(decodeURIComponent(a.source_page).replace(/_/g,' ').toLowerCase()));
 assert.equal(a.old_curation,'APPROVED_BY_USER_2026_11_03');
 const r=gallery.records.find(x=>x.id===a.artwork_id);
 assert(r && r.owner_selected_artwork===true);
 assert.equal(r.record_status,'APPROVED_BY_USER_2026_11_03');
 assert.equal(r.rights_note,a.previous_photo_rights_note,'original historical rights record must be preserved exactly');
 assert.equal(r.image.src,'./'+a.derivative_path.slice('site/'.length));
 assert.equal(r.image.usage,'GALLERY_ONLY__USER_SELECTED_WORK__NO_NEW_PRAYER_DEFAULT');
 assert(r.image.source_note.includes('not a new museum-level'));
 const p=prov.sources.find(x=>x.artwork_id===a.artwork_id&&x.path===a.derivative_path);
 assert(p);
 assert.equal(p.sha256,a.derivative_sha256);
 assert.equal(p.git_blob_sha,a.derivative_git_blob_sha);
 assert.equal(p.commons_file_sha1,a.commons_sha1);
 assert.equal(p.source_image_original_bytes_retained,false);
 bytes+=b.length;
}
assert.equal(bytes,manifest.summary.new_bytes);
assert.equal(manifest.summary.new_prayer_card_assignments,0);
assert.equal(manifest.summary.new_calendar_selections,0);
assert.equal(manifest.summary.original_curatorial_records_unchanged,873);
assert.equal(manifest.summary.image_hash_mismatches,0);
const held=new Set(manifest.held.map(x=>x.artwork_id));
for(const id of held)assert(!exact.has(id),'Held source may not be released');
