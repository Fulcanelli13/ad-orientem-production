import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync,existsSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const file=p=>resolve(root,p),read=p=>readFileSync(file(p));
const json=p=>JSON.parse(read(p).toString('utf8'));
const sha=p=>createHash('sha256').update(read(p)).digest('hex');
const before=json('app-data/sacred-art/selected31-clearance-v19.json');
const after=json('app-data/sacred-art/selected31-clearance-v20.json');
const acquisitions=json('app-data/sacred-art/staged-selected31-v20/acquisition-results.v20.json');
const v13=json('site/gallery/selected31-reviewed-images.v13.json');
const v14=json('site/gallery/selected31-reviewed-images.v14.json');
const v20=json('site/gallery/selected31-reviewed-images.v20.json');
const catalogue=json('site/gallery/catalogue.v1.json');
const provenance=json('site/gallery/image-provenance.v1.json');
const js=read('site/gallery/gallery.js').toString('utf8');
assert.equal(catalogue.counts.total_records,873);
assert(catalogue.counts.distinct_locally_hosted_paintings>=392);
assert.equal(catalogue.counts.distinct_locally_hosted_paintings,provenance.local_image_count);
assert.equal(before.records.length,31);
assert.equal(after.records.length,31);
assert.equal(after.schema,'ao.sacred-art.selected31-clearance.v20');
assert.deepEqual(after.counts,{main_preserved:6,overlay_eligible:8,source_only_holds:17});
assert.deepEqual(new Set(after.records.map(r=>r.review_artwork_id)),new Set(before.records.map(r=>r.review_artwork_id)));
const changed=after.records.filter(row=>row.disposition!==before.records.find(x=>x.review_artwork_id===row.review_artwork_id)?.disposition);
assert.deepEqual(changed.map(x=>x.review_artwork_id).sort(),['cana-vermeyen','trans-raphael']);
assert.equal(changed.find(x=>x.review_artwork_id==='cana-vermeyen').disposition,'DRAFT_GALLERY_ELIGIBLE');
assert.equal(changed.find(x=>x.review_artwork_id==='trans-raphael').disposition,'CURRENT_MAIN_PRESERVE');
assert.equal(changed.find(x=>x.review_artwork_id==='trans-raphael').gallery_record_id,'RELEASED::class-i-2026:vatican-mv-40333');
assert(existsSync(file(changed.find(x=>x.review_artwork_id==='trans-raphael').gallery_image_file)));
assert.equal(acquisitions.acquired_count,1);
assert.equal(acquisitions.held_count,2);
assert.deepEqual(acquisitions.holds.map(x=>x.review_artwork_id).sort(),['cana-francken','tri-dolci']);
const source=acquisitions.records[0];
assert.equal(source.review_artwork_id,'cana-vermeyen');
assert.deepEqual(source.source_dimensions,[4000,3132]);
assert.deepEqual(source.derivative_dimensions,[2000,1566]);
assert.equal(source.iiif_id,'crXuY');
assert.equal(sha(source.source_path),source.source_sha256);
assert.equal(sha(source.derivative_path),source.derivative_sha256);
assert.equal(source.status,'SOURCE_ARCHIVE_ONLY__NO_SITE_OR_PRAYER_BINDING');
assert.equal(v20.records.length,1);
assert.equal(v20.provenance.length,1);
assert.equal(v20.schema,'ao.sacred-art.selected31-gallery-overlay.v20');
const record=v20.records[0],proof=v20.provenance[0];
assert.equal(record.id,'REVIEW31::cana-vermeyen');
assert(record.owner_selected_artwork);
assert.equal(record.exact_prayer_cards.length,0);
assert.equal(record.prayer_parts.length,0);
assert.equal(record.eligible_card_count,0);
assert.equal(record.parent_prayer_candidates.length,0);
assert.equal(record.image.src,'./gallery/images/selected31-v20-cana-vermeyen-2000.webp');
assert.equal(sha('site/'+record.image.src.slice(2)),source.derivative_sha256);
assert.equal(proof.source_sha256,source.source_sha256);
assert.equal(proof.derivative_sha256,source.derivative_sha256);
assert.equal(proof.gallery_file,'site/gallery/images/selected31-v20-cana-vermeyen-2000.webp');
assert.equal(v13.records.length,5);
assert.equal(v14.records.length,1);
assert.equal(v14.image_patches.length,1);
assert.equal(new Set([...(v13.records),...(v14.records),...(v20.records)].map(x=>x.id)).size,7);
for(const x of after.records){
  assert.equal(x.automatic_prayer_card_assignment,false);
  if(x.disposition==='HOLD_SOURCE_ONLY'){
    assert(x.source_archive_path && existsSync(file(x.source_archive_path)));
    assert(!x.gallery_image_file);
  }
}
assert(js.includes('selected31-reviewed-images.v20.json'));
assert(js.includes('legacyRecordCount !== 873 || addedRecords !== 7 || addedImages !== 8'));
